#!/usr/bin/env node

/**
 * Generate espn-crests.json from the live ESPN API.
 *
 * Run from any machine with ESPN access (not behind dev.opt's DNS block):
 *   node scripts/fetch-espn-crests.mjs
 *
 * Validates every badge URL against the CDN (HEAD request) and drops 404s.
 * Output: data/espn-crests.json
 */

import { writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, "../data/espn-crests.json");

/** Our 11 competitions mapped to ESPN league slugs. */
const LEAGUES = {
  "premier-league": "eng.1",
  "la-liga": "esp.1",
  "serie-a": "ita.1",
  bundesliga: "ger.1",
  "ligue-1": "fra.1",
  "champions-league": "uefa.champions",
  "europa-league": "uefa.europa",
  "conference-league": "uefa.europa.conf",
  eredivisie: "ned.1",
  "liga-portugal": "por.1",
  championship: "eng.2",
};

const TIMEOUT_MS = 15_000;

async function fetchTeams(slug) {
  const url = `https://site.api.espn.com/apis/site/v2/sports/soccer/${slug}/teams`;
  const res = await fetch(url, { signal: AbortSignal.timeout(TIMEOUT_MS) });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const json = await res.json();
  const entries = json?.sports?.[0]?.leagues?.[0]?.teams ?? [];
  return entries
    .map((e) => {
      const t = e?.team;
      if (!t || typeof t.displayName !== "string") return null;
      const id = String(t.id ?? "");
      if (!id) return null;
      return {
        id,
        name: t.displayName,
        url: `https://a.espncdn.com/i/teamlogos/soccer/500/${id}.png`,
      };
    })
    .filter(Boolean);
}

async function validateUrl(url) {
  try {
    const res = await fetch(url, {
      method: "HEAD",
      signal: AbortSignal.timeout(8_000),
    });
    return res.ok;
  } catch {
    return false;
  }
}

async function main() {
  const teams = {};
  let total = 0;
  let valid = 0;

  for (const [comp, slug] of Object.entries(LEAGUES)) {
    process.stdout.write(`${comp} (${slug})... `);
    try {
      const raw = await fetchTeams(slug);
      process.stdout.write(`${raw.length} teams, validating... `);

      const verified = [];
      for (const t of raw) {
        total++;
        if (await validateUrl(t.url)) {
          valid++;
          verified.push(t);
        }
      }

      teams[comp] = verified;
      process.stdout.write(`${verified.length} OK\n`);
    } catch (err) {
      console.log(`FAILED: ${err.message}`);
      teams[comp] = [];
    }
  }

  const out = {
    generatedAt: new Date().toISOString(),
    note: `Auto-generated by fetch-espn-crests.mjs. ${valid}/${total} URLs validated.`,
    teams,
  };

  writeFileSync(OUT, JSON.stringify(out, null, 2) + "\n");
  console.log(`\nWrote ${OUT}`);
  console.log(`${valid}/${total} URLs valid across ${Object.keys(teams).length} competitions`);
}

main().catch((err) => {
  console.error("Fatal:", err);
  process.exit(1);
});
